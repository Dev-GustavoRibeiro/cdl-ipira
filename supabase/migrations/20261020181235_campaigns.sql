-- Campanhas: entidade própria, vinculável a notícias, eventos e álbuns
create table if not exists public.campaigns (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  summary text,
  description text,
  cover_image text,
  start_date date not null,
  end_date date,
  is_featured boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaigns_dates_check check (end_date is null or end_date >= start_date)
);

alter table public.campaigns enable row level security;

drop policy if exists campaigns_public_read on public.campaigns;
create policy campaigns_public_read on public.campaigns
  for select to public using (is_active = true);

drop trigger if exists update_campaigns_updated_at on public.campaigns;
create trigger update_campaigns_updated_at before update on public.campaigns
  for each row execute function public.update_updated_at_column();

alter table public.news   add column if not exists campaign_id bigint references public.campaigns(id) on delete set null;
alter table public.events add column if not exists campaign_id bigint references public.campaigns(id) on delete set null;
alter table public.albums add column if not exists campaign_id bigint references public.campaigns(id) on delete set null;

create index if not exists news_campaign_id_idx   on public.news(campaign_id);
create index if not exists events_campaign_id_idx on public.events(campaign_id);
create index if not exists albums_campaign_id_idx on public.albums(campaign_id);
